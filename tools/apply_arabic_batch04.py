def js_payload(text: str) -> str:
    marker = "window.PERSON_I18N = "
    if marker not in text:
        raise RuntimeError("Could not find PERSON_I18N marker in JS.")
    return text.split(marker, 1)[1].rstrip().rstrip(";").strip()

def main():
    if not DATA.exists():
        raise SystemExit(f"Missing: {DATA}")
    d = json.loads(DATA.read_text(encoding="utf-8"))
    people = d.get("people", {})
    missing = [k for k in PATCH if k not in people]
    if missing:
        raise SystemExit("Missing exact project keys: " + ", ".join(missing))

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    BACKUP.mkdir(parents=True, exist_ok=True)
    shutil.copy2(DATA, BACKUP / f"person_i18n_ar_batch04_{stamp}.json")
    if JS.exists():
        shutil.copy2(JS, BACKUP / f"person_i18n_ar_batch04_{stamp}.js")

    changes = 0
    for person, fields in PATCH.items():
        langs = people[person].setdefault("languages", {})
        ar = dict(langs.get("ar", {}))
        for field, value in fields.items():
            if ar.get(field) != value:
                ar[field] = value
                changes += 1
        langs["ar"] = ar

    DATA.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    if JS.exists():
        JS.write_text("window.PERSON_I18N = " + json.dumps(d, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
        js = json.loads(js_payload(JS.read_text(encoding="utf-8")))
        if js != d:
            raise SystemExit("JSON↔JS semantic equality FAILED.")
    print(f"Arabic Batch 04 applied: {len(PATCH)} people, {changes} field changes.")
    print("JSON↔JS semantic equality: PASS")

if __name__ == "__main__":
    main()
