def load_json():
    with JSON_PATH.open("r", encoding="utf-8-sig") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise RuntimeError("person_i18n.json is not an object")
    return data

def load_js():
    text = JS_PATH.read_text(encoding="utf-8-sig")
    prefix = "window.PERSON_I18N = "
    if not text.startswith(prefix):
        raise RuntimeError("Could not parse person_i18n.js")
    payload = text[len(prefix):].strip()
    if payload.endswith(";"):
        payload = payload[:-1].rstrip()
    return json.loads(payload)

def rebuild_js(data):
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    JS_PATH.write_text(
        "window.PERSON_I18N = " + payload + ";\n",
        encoding="utf-8",
    )

def main():
    data = load_json()

    missing = [name for name in BATCH if name not in data]
    if missing:
        raise RuntimeError("Missing exact person keys: " + ", ".join(missing))

    for name, content in BATCH.items():
        if not isinstance(data[name], dict):
            raise RuntimeError(f"Invalid profile: {name}")
        if not isinstance(data[name].get("languages"), dict):
            raise RuntimeError(f"Missing languages object: {name}")
        if "ar" not in data[name]["languages"]:
            raise RuntimeError(f"Missing Arabic record: {name}")

    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    json_backup = BACKUP_DIR / f"person_i18n_ar_batch08b_{stamp}.json"
    js_backup = BACKUP_DIR / f"person_i18n_ar_batch08b_{stamp}.js"

    json_backup.write_text(JSON_PATH.read_text(encoding="utf-8"), encoding="utf-8")
    js_backup.write_text(JS_PATH.read_text(encoding="utf-8"), encoding="utf-8")

    changes = 0

    for name, content in BATCH.items():
        ar = data[name]["languages"]["ar"]

        for field, value in content.items():
            if ar.get(field) != value:
                ar[field] = value
                changes += 1

        ar["language"] = "ar"

    JSON_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    rebuild_js(data)

    js_data = load_js()

    if js_data != data:
        JSON_PATH.write_text(
            json_backup.read_text(encoding="utf-8"),
            encoding="utf-8",
        )
        JS_PATH.write_text(
            js_backup.read_text(encoding="utf-8"),
            encoding="utf-8",
        )
        raise RuntimeError("JSON↔JS semantic equality FAILED — rolled back")

    print(f"Arabic Batch 08B applied: {len(BATCH)} people, {changes} field changes.")
    print("JSON↔JS semantic equality: PASS")
    print(f"Backup JSON: {json_backup}")
    print(f"Backup JS:   {js_backup}")

if __name__ == "__main__":
    main()
