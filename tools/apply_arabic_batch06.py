    d=json.loads(DATA.read_text(encoding="utf-8")); people=d["people"]
    missing=[k for k in PATCH if k not in people]
    if missing: raise SystemExit("Missing exact project keys: "+", ".join(missing))
    ts=datetime.now().strftime("%Y%m%d_%H%M%S"); BACKUP.mkdir(parents=True,exist_ok=True)
    shutil.copy2(DATA,BACKUP/f"person_i18n_ar_batch06_{ts}.json")
    if JS.exists(): shutil.copy2(JS,BACKUP/f"person_i18n_ar_batch06_{ts}.js")
    changes=0
    for person,fields in PATCH.items():
        ar=dict(people[person].setdefault("languages",{}).get("ar",{}))
        for f,v in fields.items():
            if ar.get(f)!=v: ar[f]=v; changes+=1
        people[person]["languages"]["ar"]=ar
    DATA.write_text(json.dumps(d,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    if JS.exists():
        JS.write_text("window.PERSON_I18N = "+json.dumps(d,ensure_ascii=False,indent=2)+";\n",encoding="utf-8")
        if json.loads(payload(JS.read_text(encoding="utf-8")))!=d: raise SystemExit("JSON↔JS semantic equality FAILED")
