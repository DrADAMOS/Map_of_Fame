FIELDS = ("hint","bio","achievements","key_facts","wars","historical_significance")

def load_json():
    data = json.loads(JSON_PATH.read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict) or not isinstance(data.get("people"), dict):
        raise RuntimeError("Invalid person_i18n.json structure")
    return data

def load_js():
    text = JS_PATH.read_text(encoding="utf-8-sig")
    prefix = "window.PERSON_I18N = "
    if not text.startswith(prefix):
        raise RuntimeError("Could not parse person_i18n.js")
    payload = text[len(prefix):].strip()
    if payload.endswith(";"):
        payload = payload[:-1].rstrip()
    parsed = json.loads(payload)
    if not isinstance(parsed, dict):
        raise RuntimeError("PERSON_I18N payload is not an object")
    return parsed

def rebuild_js(data):
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    JS_PATH.write_text("window.PERSON_I18N = " + payload + ";\n", encoding="utf-8")

data = load_json()

for name, patch in BATCH.items():
    if name not in data["people"]:
        raise RuntimeError(f"Missing exact person key: {name}")
    ar = data["people"][name].get("languages", {}).get("ar")
    if not isinstance(ar, dict):
        raise RuntimeError(f"Missing Arabic record: {name}")
    for field in FIELDS:
        if field not in patch:
            raise RuntimeError(f"{name}: missing {field}")

timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
BACKUP_DIR.mkdir(parents=True, exist_ok=True)

backup_json = BACKUP_DIR / f"person_i18n_ar_batch08a_{timestamp}.json"
backup_js = BACKUP_DIR / f"person_i18n_ar_batch08a_{timestamp}.js"

backup_json.write_text(JSON_PATH.read_text(encoding="utf-8-sig"), encoding="utf-8")
backup_js.write_text(JS_PATH.read_text(encoding="utf-8-sig"), encoding="utf-8")

before = copy.deepcopy(data)
changes = 0

for name, patch in BATCH.items():
    ar = data["people"][name]["languages"]["ar"]
    for field in FIELDS:
        if ar.get(field) != patch[field]:
            ar[field] = copy.deepcopy(patch[field])
            changes += 1

JSON_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
rebuild_js(data)

if load_js() != data:
    JSON_PATH.write_text(json.dumps(before, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rebuild_js(before)
    raise RuntimeError("JSON↔JS semantic equality failed; changes rolled back")

print(f"Arabic Batch 08A applied: {len(BATCH)} people, {changes} field changes.")
print("JSON↔JS semantic equality: PASS")
print(f"Backup JSON: {backup_json}")
print(f"Backup JS:   {backup_js}")
