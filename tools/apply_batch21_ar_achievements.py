def normalize_name(value: str) -> str:
    try:
        return value.encode("latin1").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return value


def find_person(people: dict, target: str) -> dict | None:
    for person in people.values():
        if not isinstance(person, dict):
            continue
        languages = person.get("languages")
        if not isinstance(languages, dict):
            continue
        en = languages.get("en")
        if not isinstance(en, dict):
            continue
        name = en.get("name")
        if isinstance(name, str) and (
            name == target or normalize_name(name) == target
        ):
            return person
    return None


def main() -> None:
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    people = data["people"]

    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = BACKUP_DIR / f"person_i18n_before_batch21_ar_achievements_{stamp}.json"
    shutil.copy2(JSON_PATH, backup)

    missing: list[str] = []
    changed = 0

    for name, achievements in ACHIEVEMENTS.items():
        person = find_person(people, name)
        if person is None:
            missing.append(name)
            continue

        languages = person.setdefault("languages", {})
        ar = languages.setdefault("ar", {})
        if ar.get("achievements") != achievements:
            ar["achievements"] = achievements
            changed += 1

    if missing:
        raise RuntimeError("Missing people:\n" + "\n".join(missing))

    JSON_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    JS_PATH.write_text(
        "/* Auto-generated from person_i18n.json. Do not edit manually. */\n"
        "window.PERSON_I18N = "
        + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )

    js_text = JS_PATH.read_text(encoding="utf-8")
    js_payload = js_text.split("window.PERSON_I18N = ", 1)[1].rsplit(";", 1)[0]
    js_data = json.loads(js_payload)

    if js_data != data:
        raise RuntimeError("JSON<->JS semantic equality FAILED")

    print(f"Batch 21 applied: {changed} people.")
    print(f"Backup JSON: {backup}")
    print("JSON<->JS semantic equality: PASS")
    print(f"Targets: {len(ACHIEVEMENTS)}")


if __name__ == "__main__":
    main()
